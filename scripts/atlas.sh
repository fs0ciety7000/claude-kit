#!/usr/bin/env bash
# kit atlas : the project's page on the documentation hub (Starlight site, private repository).
#
#   kit atlas sync [--dir D] [--dry-run]  writes src/content/docs/projets/<name>.md from project.yaml, docs/plan.md
#                                         (lots and checkboxes) and docs/memory/state.md (done, blocking, next 3), on
#                                         the branch projet/<name> of the hub repository, then opens or updates its PR
#   kit atlas page [--dir D]              prints the generated page; writes nothing
#
# The owner's clone is left alone: a detached temporary worktree carries the commit. Nothing is committed when the page
# is unchanged (the updated: date alone does not count). The page is refused if it holds an IP address, an e-mail
# address or a token-like string. Settings: ~/.config/claude-kit/atlas.conf (docs/atlas.conf.example); absent, the
# sync is skipped with a warning and exit code 0, so /ship, /retire and /handoff carry on.
set -euo pipefail
ASELF=$(readlink -f "${BASH_SOURCE[0]}")
# shellcheck disable=SC2034 # read by ship.sh: helpers only, no entry point
KIT_SHIP_SOURCED=1
# shellcheck source-path=SCRIPTDIR source=ship.sh
source "$(dirname "$ASELF")/ship.sh"

usage() { sed -n '2,12p' "$ASELF" | sed 's/^# \{0,1\}//'; }

CONF="$KIT_CONFIG/atlas.conf"
ATLAS_REPO="" ATLAS_BASE="" PAGE_DIR="src/content/docs/projets"
TODAY=${KIT_ATLAS_TODAY:-$(date +%F)}

load_atlas_conf() {
  INFRA_DIR=$(conf_req ATLAS_DIR '^/') # INFRA_DIR: ship.sh's cleanup removes the worktree from this clone
  ATLAS_REPO=$(conf_req ATLAS_REPO '^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$')
  ATLAS_BASE=$(conf ATLAS_BASE main)
  [[ $ATLAS_BASE =~ ^[A-Za-z0-9._/-]+$ ]] || die "atlas.conf : ATLAS_BASE invalide"
  [[ -d $INFRA_DIR/.git || -f $INFRA_DIR/.git ]] || die "ATLAS_DIR n'est pas un clone git : $INFRA_DIR"
}

# ---------- page ----------
yq_str() { local s=${1//\\/\\\\}; printf '"%s"' "${s//\"/\\\"}"; } # YAML double-quoted scalar

plan_progress() { # plan.md -> "lot<TAB>done<TAB>total" per section with checkboxes, then "TOTAL<TAB>done<TAB>total"
  [[ -f $1 ]] || return 0
  awk '
    function flush() { if (n) printf "%s\t%d\t%d\n", sec, d, n; n = 0; d = 0 }
    /^```/ { fence = !fence; next }
    fence { next }
    /^## / { flush(); sec = substr($0, 4); next }
    /^[ \t]*[-*] \[[ xX]\]/ { n++; N++; if ($0 ~ /\[[xX]\]/) { d++; D++ } }
    END { flush(); printf "TOTAL\t%d\t%d\n", D, N }
  ' "$1"
}

state_field() { # state.md label -> value lines: inline text, then sub-items (one per line, markers removed)
  [[ -f $1 ]] || return 0
  LABEL=$2 awk '
    BEGIN { l = ENVIRON["LABEL"] }
    on && /^[-*] / { exit }
    on && /^[ \t]+([-*]|[0-9]+[.)]) / { sub(/^[ \t]+([-*]|[0-9]+[.)])[ \t]+/, ""); print; next }
    on && /^[ \t]*$/ { next }
    on { exit }
    index($0, "- **" l "**") == 1 {
      on = 1; v = substr($0, length(l) + 7); sub(/^[ \t]*:[ \t]*/, "", v); sub(/[ \t]+$/, "", v)
      if (v != "" && v != "—" && v != "-") print v
    }
  ' "$1"
}

short() { local s=$1; ((${#s} <= 240)) || s="${s:0:237}..."; printf '%s' "$s"; }

page_status() { # values accepted by the atlas schema: brouillon, actif, en-pause, archive
  local s
  s=$(pget status)
  case $s in brouillon | actif | en-pause | archive) ;; *) s= ;; esac
  if [[ -z $s ]]; then
    if [[ $P_EXPOSE != none ]]; then s=actif
    elif [[ -n $P_UUID ]]; then s=archive
    else s=brouillon; fi
  fi
  printf '%s' "$s"
}

gen_page() { # -> page on stdout
  local size stack desc tags t line lot d n first=1 total_d=0 total_n=0 label v items i
  size=$(pget size) stack=$(pget stack) desc=$(pget description)
  [[ -n $desc ]] || desc="Projet $P_NAME${size:+, taille $size}${stack:+, pile $stack}."
  tags="projet"
  for t in $(printf '%s' "$stack" | tr '[:upper:]' '[:lower:]' | tr -c 'a-z0-9-' ' '); do
    [[ " $tags " == *" $t "* ]] || tags="$tags $t"
  done
  printf -- '---\n'
  printf 'title: %s\n' "$(yq_str "$P_NAME")"
  printf 'description: %s\n' "$(yq_str "$desc")"
  printf 'type: projet\n'
  printf 'updated: %s\n' "$TODAY"
  printf 'tags: [%s]\n' "$(echo "$tags" | sed 's/ /, /g')"
  printf 'status: %s\n' "$(page_status)"
  printf -- '---\n\n'
  printf '%s\n\n' "<!-- Generated by kit atlas sync from the project's repository: edit the project, then sync again. -->"
  printf '## Fiche\n\n'
  printf -- '- **Taille** : %s\n' "${size:-—}"
  printf -- '- **Pile** : %s\n' "${stack:-—}"
  printf -- '- **Exposition** : %s\n' "$P_EXPOSE"
  case $P_EXPOSE in
    public|access) printf -- '- **URL** : https://%s\n' "$P_DOMAIN" ;;
    tailnet) printf -- '- **URL** : nom du service sur le tailnet\n' ;; # internal names stay out of the hub
  esac
  printf '\n## Avancement\n\n'
  local prog
  prog=$(plan_progress "$DIR/docs/plan.md")
  if [[ -z $prog ]]; then
    printf 'Pas de plan (docs/plan.md absent).\n'
  else
    while IFS=$'\t' read -r lot d n; do
      if [[ $lot == TOTAL ]]; then total_d=$d total_n=$n; fi
    done <<<"$prog"
    if ((total_n == 0)); then printf 'Aucune tâche dans docs/plan.md.\n'
    else
      printf '%d/%d tâches (%d %%).\n\n' "$total_d" "$total_n" $((total_d * 100 / total_n))
      while IFS=$'\t' read -r lot d n; do
        [[ $lot == TOTAL ]] || printf -- '- %s : %d/%d\n' "$lot" "$d" "$n"
      done <<<"$prog"
    fi
  fi
  printf '\n## État\n\n'
  if [[ ! -f $DIR/docs/memory/state.md ]]; then printf '%s\n' "Pas d'état (docs/memory/state.md absent)."; return 0; fi
  for label in Fait "En cours" Bloquant; do
    v=$(state_field "$DIR/docs/memory/state.md" "$label" | paste -sd ';' - | sed 's/;/ ; /g')
    printf -- '- **%s** : %s\n' "$label" "$(short "${v:-—}")"
  done
  items=()
  while IFS= read -r line; do
    [[ -n $line ]] || continue
    if ((first)) && [[ $line == *" ; "* ]]; then # inline list "a ; b ; c"
      while [[ $line == *" ; "* ]]; do items+=("${line%% ; *}"); line=${line#* ; }; done
    fi
    items+=("$line")
    first=0
  done < <(state_field "$DIR/docs/memory/state.md" "Prochaines étapes")
  if ((${#items[@]} == 0)); then printf -- '- **Prochaines étapes** : —\n'; return 0; fi
  printf -- '- **Prochaines étapes** :\n'
  for ((i = 0; i < ${#items[@]} && i < 3; i++)); do printf '  %d. %s\n' $((i + 1)) "$(short "${items[i]}")"; done
}

# Identifying data and secrets: kinds and line numbers are reported, never the matched text.
privacy_check() { # file
  local f=$1 found="" kind re ln
  local -a kinds=(
    "adresse IPv4|(^|[^0-9.])([0-9]{1,3}\.){3}[0-9]{1,3}([^0-9.]|$)"
    "adresse IPv6|(^|[^0-9A-Za-z:])([0-9A-Fa-f]{1,4}:){7}[0-9A-Fa-f]{1,4}|(^|[^0-9A-Za-z:])([0-9A-Fa-f]{1,4}:){1,6}:([0-9A-Fa-f]{1,4}(:[0-9A-Fa-f]{1,4})*)?([^0-9A-Za-z:]|$)"
    "adresse e-mail|[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}"
    "jeton ou clé|AKIA[0-9A-Z]{16}|-----BEGIN [A-Z ]*PRIVATE KEY-----|AGE-SECRET-KEY-1[A-Z0-9]{20,}|gh[pousr]_[A-Za-z0-9]{20,}|github_pat_[A-Za-z0-9_]{20,}|sk-[A-Za-z0-9_-]{20,}|xox[baprs]-[A-Za-z0-9-]{10,}|glpat-[A-Za-z0-9_-]{20,}|eyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}"
    "identifiant (UUID)|[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}"
  )
  for kind in "${kinds[@]}"; do
    re=${kind#*|}
    ln=$(grep -nE -- "$re" "$f" | cut -d: -f1 | paste -sd, - || true)
    [[ -z $ln ]] || found="$found ${kind%%|*} (ligne $ln) ;"
  done
  # Long random-looking strings (32+ characters mixing upper case, lower case and digits, no dash): token-like.
  ln=$(grep -noE '[A-Za-z0-9_+/=]{32,}' "$f" | awk -F: '$2 ~ /[0-9]/ && $2 ~ /[A-Z]/ && $2 ~ /[a-z]/ { print $1 }' | sort -un | paste -sd, - || true)
  [[ -z $ln ]] || found="$found chaîne de type jeton (ligne $ln) ;"
  [[ -z $found ]] || die "page refusée, donnée identifiante ou secret :${found% ;} ; corrige la source (project.yaml, docs/plan.md, docs/memory/state.md), rien n'a été écrit"
}

same_page() { # a b : identical but for the updated: line
  diff -q <(grep -v '^updated: ' "$1") <(grep -v '^updated: ' "$2") >/dev/null 2>&1
}

# ---------- sync ----------
atlas_ref() { # PR branch on origin if present and not merged into the base, else the base
  if git -C "$INFRA_DIR" rev-parse -q --verify "refs/remotes/origin/$1" >/dev/null \
    && ! git -C "$INFRA_DIR" merge-base --is-ancestor "origin/$1" "origin/$ATLAS_BASE" 2>/dev/null; then echo "origin/$1"
  else echo "origin/$ATLAS_BASE"; fi
}
atlas_stale() { # branch : squash-merged PR branch still on origin, no PR open -> stop (a new base would need a force push)
  local q="repos/$ATLAS_REPO/pulls?head=${ATLAS_REPO%%/*}:$1" open merged
  open=$("$GH" api "$q&state=open" --jq 'length') || die "lecture des PR en échec (gh)"
  [[ $open == 0 ]] || return 0
  merged=$("$GH" api "$q&state=closed" --jq '[.[] | select(.merged_at != null)] | length') || die "lecture des PR en échec (gh)"
  [[ $merged == 0 ]] || die "branche $1 déjà fusionnée mais encore présente sur $ATLAS_REPO : supprime-la sur GitHub, puis relance (rien n'a été écrit)"
}

atlas_sync() { # mode: dry | real
  local mode=$1 branch="projet/$P_NAME" rel="$PAGE_DIR/$P_NAME.md" ref page old wt pr title body
  page="$(tmpd)/page.md"
  gen_page >"$page"
  privacy_check "$page"
  echo "Atlas : $rel sur $ATLAS_REPO (branche $branch)"
  if [[ $mode == real ]]; then
    need "$GH" "Installe GitHub CLI (gh)."
    git -C "$INFRA_DIR" fetch -q --prune origin || die "git fetch du dépôt atlas en échec"
  fi
  ref=$(atlas_ref "$branch")
  if [[ $mode == real && $ref != "origin/$ATLAS_BASE" ]]; then atlas_stale "$branch"; fi
  old="$(tmpd)/old.md"
  git -C "$INFRA_DIR" show "$ref:$rel" >"$old" 2>/dev/null || : >"$old"
  local changed=1
  if [[ -s $old ]] && same_page "$old" "$page"; then changed=0; fi
  if [[ $mode == dry ]]; then
    echo "  (d'après $ref du clone local, sans git fetch)"
    if ((changed)); then diff -u --label "a/$rel" --label "b/$rel" "$old" "$page" | sed 's/^/    /' || true
      echo "  PR à ouvrir ou mettre à jour : « projet: $P_NAME » ($branch -> $ATLAS_BASE)"
    else echo "  page à jour : rien à écrire"; fi
    echo "Rien n'a été écrit (--dry-run)."
    return 0
  fi
  if ((changed)); then
    wt="$(tmpd)/wt"
    git -C "$INFRA_DIR" worktree add -q --detach "$wt" "$ref" >/dev/null 2>&1 || die "git worktree add en échec dans $INFRA_DIR"
    WT_DIR=$wt
    mkdir -p "$wt/$PAGE_DIR"
    [[ ! -L $wt/$rel ]] || die "$rel est un lien symbolique dans le dépôt atlas : refusé"
    cp "$page" "$wt/$rel"
    git -C "$wt" add -- "$rel"
    git -C "$wt" commit -q -m "docs(projets): $P_NAME" -m "Generated by kit atlas sync from $P_NAME." || die "commit en échec dans le dépôt atlas"
    announce "push de $branch sur $ATLAS_REPO (effet : branche de PR ; retour arrière : fermer la PR)"
    git -C "$wt" push -q origin "HEAD:refs/heads/$branch" || die "push en échec"
  elif [[ $ref == "origin/$ATLAS_BASE" ]]; then
    ok "page à jour : rien à écrire"
    return 0
  else
    echo "  page déjà à jour sur $branch"
  fi
  pr=$("$GH" api "repos/$ATLAS_REPO/pulls?head=${ATLAS_REPO%%/*}:$branch&state=open" --jq '.[0].html_url // empty') || die "lecture des PR en échec (gh)"
  if [[ -n $pr ]]; then
    ok "PR mise à jour : $pr"
  else
    title="projet: $P_NAME"
    body=$(printf 'Page `%s` generated by `kit atlas sync` from `project.yaml`, `docs/plan.md` and `docs/memory/state.md`.\n\nThe owner reviews and merges.' "$rel")
    announce "PR « $title » sur $ATLAS_REPO (effet : revue ; retour arrière : fermer la PR)"
    pr=$("$GH" api -X POST "repos/$ATLAS_REPO/pulls" -f title="$title" -f head="$branch" -f base="$ATLAS_BASE" -f body="$body" --jq .html_url) \
      || die "création de la PR en échec (gh)"
    ok "PR ouverte : $pr"
  fi
}

main() {
  local sub=${1:-help}
  shift || true
  case $sub in
    help|-h|--help) usage; return 0 ;;
    sync|page) ;;
    *) usage >&2; exit 1 ;;
  esac
  while (($#)); do
    case $1 in
      --dir) DIR=${2:?"dossier manquant"}; shift ;;
      --dry-run) DRY=1 ;;
      *) die "option inconnue : $1" ;;
    esac
    shift
  done
  [[ -d $DIR ]] || die "dossier introuvable : $DIR"
  DIR=$(cd "$DIR" && pwd)
  load_project
  if [[ $sub == page ]]; then
    local p
    p="$(tmpd)/page.md"
    gen_page >"$p"
    privacy_check "$p"
    cat "$p"
    return 0
  fi
  if [[ ! -f $CONF ]]; then
    warn "atlas.conf absent ($CONF, modèle docs/atlas.conf.example du kit) : page projet non synchronisée"
    return 0
  fi
  load_conf
  load_atlas_conf
  if ((DRY)); then atlas_sync dry; else atlas_sync real; fi
}
main "$@"
